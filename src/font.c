#undef V

const uint8_t *font_glyph(int ch) {
    ch &= 0xFF;
    for (unsigned k = 0; k < sizeof BOX / sizeof BOX[0]; k++)
        if (BOX[k][0] == ch) return BOX[k] + 1;
    if (ch >= 'a' && ch <= 'z') ch -= 32;      /* v0: lowercase -> uppercase */
    if (ch < 32 || ch > '`') return G[0];
    return G[ch - 32];
}
